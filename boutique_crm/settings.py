    raise ImproperlyConfigured(
        "USE_LOCAL_DB=True with DEBUG=False. Refusing to point a production "
        "process at a development database. Unset USE_LOCAL_DB and set "
        "DB_NAME, DB_USER, DB_PASSWORD and DB_HOST."
    )

